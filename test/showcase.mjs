// Three design screenshots for one brand on iPhone 13: home, areas step, done screen.
// node test/showcase.mjs <baseUrl> <slug> <outDir>
import { webkit, devices } from "playwright";
import path from "node:path";
import fs from "node:fs";
const [BASE, SLUG, OUT] = process.argv.slice(2);
const FIX = path.resolve("test/fixtures");
fs.mkdirSync(OUT, { recursive: true });
const b = await webkit.launch();
const ctx = await b.newContext({ ...devices["iPhone 13"], timezoneId: "America/Edmonton", locale: "en-CA", acceptDownloads: true });
const page = await ctx.newPage();
const T = (hhmm) => new Date(`2026-12-14T${hhmm}:00-07:00`); // Alberta site time, December (MST)
await page.clock.install({ time: T("07:02") });
const btn = (re) => page.getByRole("button", typeof re === "string" ? { name: re, exact: true } : { name: re });
const settle = () => page.waitForTimeout(900);
await page.goto(`${BASE}?c=${SLUG}`, { waitUntil: "networkidle" });
await settle();
await page.screenshot({ path: path.join(OUT, "1 - Home.png") });
await btn(/Start a site visit/).click();
await page.locator("#property").fill("Kestrel Court Apartments");
await page.locator("#address").fill("1450 Kestrel Way SW, Calgary, AB");
await page.locator("#crew").fill("Dana Mercer, Jordan Alvarez");
await btn(/^Next/).click();
for (const a of ["Walkways and sidewalks", "Entrances and landings", "Stairs", "Parking lot", "Fire exits"]) await btn(a).click();
await btn("Shovel").click(); await btn("Plow").click();
await page.evaluate(() => window.scrollTo(0, 0)); await settle();
await page.screenshot({ path: path.join(OUT, "2 - Areas cleared.png") });
await btn(/^Next/).click();
await btn("Treated salt").first().click();
await page.locator("input[inputmode=decimal]").first().fill("60");
await btn(/^Next/).click();
await page.locator("#temp").fill("-14"); await page.locator("#snow").fill("6"); await btn("Light snow").click();
await btn(/^Next/).click();
await page.locator('[data-photo-input="after"]').setInputFiles([path.join(FIX, "after-walkway.jpg"), path.join(FIX, "after-stairs.jpg")]);
await page.waitForFunction(() => document.querySelectorAll(".pcell img").length >= 2, null, { timeout: 30000 });
await page.clock.setSystemTime(T("08:04"));
await btn(/^Next/).click();
await btn("Now").click();
await page.locator("#signName").fill("Dana Mercer");
await page.locator("#signRole").fill("Site supervisor");
await page.locator(".sig-frame").scrollIntoViewIfNeeded();
const c = await page.locator(".sig-canvas").boundingBox();
await page.mouse.move(c.x + 30, c.y + 110); await page.mouse.down();
for (let i = 1; i <= 24; i++) await page.mouse.move(c.x + 30 + i * 10, c.y + 110 - Math.sin(i / 2.5) * 30);
await page.mouse.up();
await btn(/Finish and make report/).click();
await page.getByText("Visit logged").waitFor({ timeout: 60000 });
await settle();
await page.screenshot({ path: path.join(OUT, "3 - Visit logged.png") });
console.log("saved 3 screens to", OUT);
await b.close();
